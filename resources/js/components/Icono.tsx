interface PropsIcono extends LucideProps {
    nombre?: string | null;
}

export default function Icono({ nombre, ...props }: PropsIcono) {
    const Componente = (nombre && ICONOS[nombre]) || File;

    return <Componente aria-hidden="true" {...props} />;
}
